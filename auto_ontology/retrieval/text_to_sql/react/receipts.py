"""Allowlisted decision evidence from one ReAct episode."""

from dataclasses import dataclass
from enum import StrEnum
from typing import Literal

from auto_ontology.retrieval.text_to_sql.react.mode import EpisodeMode, ToolName

EpisodeEndReason = Literal[
    "submitted",
    "submitted_draft",
    "predicted",
    "no_submission",
    "budget_exhausted",
    "model_error",
]


class ToolOutcome(StrEnum):
    """What the loop observed at the dispatch boundary.

    RETURNED means a non-answering tool produced an observation. It does not
    imply that SQL ran or that a search found anything. DECLINED means an
    answering tool returned without an accepted submission or prediction.
    """

    RETURNED = "returned"
    ANSWERED = "answered"
    DECLINED = "declined"
    NOT_OFFERED = "not_offered"
    WRONG_ARGUMENTS = "wrong_arguments"
    RAISED = "raised"
    DUPLICATE = "duplicate"
    BUDGET_EXHAUSTED = "budget_exhausted"


@dataclass(frozen=True)
class ToolDecision:
    """Call identity is scoped to the receipt and generated by the loop."""

    call_id: int
    tool: ToolName | None
    outcome: ToolOutcome
    source: Literal["model", "budget_fallback"] = "model"


@dataclass(frozen=True)
class EpisodeReceipt:
    """Structured evidence that can be serialized without the raw trajectory."""

    run_id: str
    mode: EpisodeMode
    end_reason: EpisodeEndReason
    decisions: tuple[ToolDecision, ...]
