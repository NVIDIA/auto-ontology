#: Dimensionality of the embedding model (`nvidia/llama-nemotron-embed-vl-1b-v2`).
#: Not a tuning knob -- it is what the model emits, and a column declared at any
#: other width rejects every insert.
EMBEDDING_DIMENSIONS = 2048


#: Columns that exist for vector search and are never part of an entity's
#: user-facing properties. `select(table)` returns every column, so any read
#: that means "all of this node's properties" has to subtract these -- otherwise
#: a node-detail API response carries 2048 floats (~8KB) per row.
INTERNAL_COLUMNS = frozenset(
    {
        "embedding",
        "embedding_text",
        "embedding_database_name",
        "embedding_metadata",
    }
)


def public_columns(table) -> list:
    """Every column of *table* except the vector-search internals."""
    return [c for c in table.c if c.name not in INTERNAL_COLUMNS]


def _embedding_columns() -> tuple[Column, ...]:
    """Vector-search columns, carried by every embeddable entity.

    These live on the entity itself rather than in a side table, which is what
    makes an embedding subject to the same ``ON DELETE CASCADE`` as the row it
    describes. The previous arrangement -- a separate collection keyed by an id
    in a JSON blob -- had no such link, so deleting a catalog row orphaned its
    vector, and retrieval kept scoring rows that no longer existed.

    All three are nullable: a row exists before it is embedded, and "not yet
    embedded" has to be representable. ``embedding IS NULL`` is the re-embed
    work queue.

    ``embedding_database_name`` is denormalised on purpose. It is the filter
    every search applies, and the relational path to it is three joins deep from
    a column (``catalog_column -> catalog_table -> catalog_schema ->
    catalog_database``) and undefined for a Term or a CustomAnalysis, which are
    not owned by one database at all.
    """
    return (
        Column("embedding", Vector(EMBEDDING_DIMENSIONS), nullable=True),
        # The exact text that was embedded, returned with every hit as ``text``.
        # Not decorative: ``generate_sql`` concatenates it into the prompt the
        # model sees, so this is the description the LLM reasons over.
        #
        # Stored rather than re-rendered from the row on read. The renderer
        # composes a table with all of its columns, so deriving it would mean a
        # join plus an aggregation per hit -- and, more importantly, a freshly
        # rendered string describes the entity *now*, while the vector describes
        # it as of the last embed. Keeping the text that actually produced the
        # vector means a hit's explanation always matches why it matched.
        Column("embedding_text", Text, nullable=True),
        Column("embedding_database_name", Text, nullable=True),
        # Whatever else the producer attached to the embedded record.
        #
        # The old collection stored arbitrary metadata in a JSON column, and
        # callers rely on it: semantic FK inference filters candidates on
        # `is_unique` and reads `table_id` / `source_column` back off each hit.
        # Promoting those to real columns would work until the next field is
        # added -- which is exactly what happened while this was being written --
        # so the general shape is kept.
        #
        # `id`, `label` and `database_name` are deliberately *not* duplicated in
        # here: those have real columns, and two copies of an identifier is one
        # too many.
        Column("embedding_metadata", JSONB, nullable=True),
    )


catalog_table = Table(
    "catalog_table",
    METADATA,
    _id(),
    Column(
        "schema_id",
        Text,
        ForeignKey(catalog_schema.c.id, ondelete="CASCADE"),
        nullable=False,
    ),
    Column("name", Text, nullable=False),
    Column("description", Text, nullable=True),
    # Set from the UI's certification checkbox, via patch_catalog_node. Easy to
    # miss, because nothing in the ingest ever writes it
    # -- it only appears once a human certifies a description. Without the
    # column the PATCH still returns 200 and the checkbox still ticks; the flag
    # is simply dropped on the way in and reads back false forever.
    _certified("description_certified"),
    # Primary key column names. A list on the node today, so a text[] here
    # rather than a join table -- nothing ever queries "which tables have this
    # pk column", and a join table would make every read a second query.
    Column("pk", ARRAY(Text), nullable=True),
    Column("table_type", Text, nullable=True),
    _imported_id(),
    UniqueConstraint("schema_id", "name", name="uq_catalog_table_schema_name"),
    *_embedding_columns(),
)

catalog_column = Table(
    "catalog_column",
    METADATA,
    _id(),
    Column(
        "table_id",
        Text,
        ForeignKey(catalog_table.c.id, ondelete="CASCADE"),
        nullable=False,
    ),
    Column("name", Text, nullable=False),
    Column("description", Text, nullable=True),
    # As on catalog_table: written only by the UI's certification checkbox.
    _certified("description_certified"),
    Column("data_type", Text, nullable=True),
    # A JSON string, read back as a string by callers. Promoting it to jsonb is
    # a deliberate follow-up with its consumers updated, not a free change.
    Column("sample_values", Text, nullable=True),
    # How the values are *written*, not what they are: 'YYMMDD', 'YYYY-MM-DD'.
    # Generic storage notation despite only date inference filling it today
    # (`gsf.semantic.date_format`) -- an address or id profiler would write the
    # same field. `data_type`/`name`/`description` say what the values mean.
    #
    # It exists because date columns are held out of sample-value profiling, so
    # nothing else in the prompt tells the model what form to compare against:
    # `950324` and `1995-03-24` are the same day and share no predicate, and a
    # wrong guess yields SQL that runs, returns nothing, and looks right.
    Column("format", Text, nullable=True),
    Column("is_unique", Boolean, nullable=True),
    # A real Boolean. It used to hold the *strings* `information_schema`
    # reports, 'YES' and 'NO', which read back as truthy either way -- so
    # `bool(stored)` was True for every column and every export claimed the
    # whole catalog was nullable. Connectors now convert at their own edge
    # (see `gsf.connectors.base.SQLDatabase.get_columns`) and NULL still means
    # "the connector could not determine it", which callers treat as nullable.
    Column("is_nullable", Boolean, nullable=True),
    # A genuine integer, despite the parser handing the write path a string --
    # something coerces on the way in.
    Column("ordinal_position", Integer, nullable=True),
    _imported_id(),
    UniqueConstraint("table_id", "name", name="uq_catalog_column_table_name"),
    *_embedding_columns(),
)

