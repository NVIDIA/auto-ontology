#: The two terminal outcomes of a semantic compilation pass, for the check
#: constraint on :data:`semantic_compilation_history` below.
#:
#: Defined here rather than in ``gsf.ingestion_service.history``, which writes
#: them: they are part of the column's definition, and the module that writes
#: the values importing them from the constraint that permits them is the only
#: arrangement in which the two cannot disagree.
RUN_SUCCEEDED = "succeeded"
RUN_FAILED = "failed"

#: Naming convention so autogenerated constraints get stable, readable names.
#: Without it Alembic emits server-assigned names that differ between databases
#: and make a downgrade unable to find what it is dropping.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# No ``schema=`` on purpose.
# Naming the default schema explicitly makes autogenerate emit permanent drift:
# metadata reports ``referent_schema='public'`` for every foreign key while
# reflection reports the default schema as ``None``, so Alembic sees 33 changed
# constraints and proposes dropping and recreating all of them, on every run,
# forever. Leaving it unset makes both sides agree. Placement is guaranteed by
# the ``search_path`` pinned on every connection (see ``gsf/dal/session.py``),
# not by luck.
METADATA = MetaData(naming_convention=NAMING_CONVENTION)

#: ``gen_random_uuid()`` is built into Postgres from 13; no pgcrypto needed.
#:
#: Parenthesised to match how Postgres *stores* the expression. Written as
#: ``gen_random_uuid()::text`` it produces identical DDL, but the catalog reads
#: back ``(gen_random_uuid())::text``, and ``alembic check`` — which compares
#: server defaults as text — then reports drift on all 14 id columns on a
#: database that is perfectly up to date. Matching the normalised form keeps
#: the drift check meaningful instead of turning off ``compare_server_default``.
_UUID_DEFAULT = text("(gen_random_uuid())::text")


def _id() -> Column:
    return Column("id", Text, primary_key=True, server_default=_UUID_DEFAULT)


def _imported_id() -> Column:
    """Id carried over from a model-interchange export.

    ``_resolve_entities_batch`` matches YAML ids against ``imported_id OR id``,
    so an id from a previous export can arrive as an *imported* id on a node
    whose own id is different. Non-unique: two databases can legitimately import
    the same source model.
    """
    return Column("imported_id", Text, nullable=True)


def _certified(name: str) -> Column:
    """A human-set certification flag.

    ``NOT NULL DEFAULT false`` rather than nullable, because every read of these
    absent means false, and making that the column's job removes the coalesce
    from each caller — and, more usefully, the chance of one forgetting it.
    """
    return Column(name, Boolean, nullable=False, server_default=text("false"))


